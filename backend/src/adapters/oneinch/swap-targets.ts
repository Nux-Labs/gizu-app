const ranks = new Map(
  Object.entries(BUY_TARGETS).map(([chainId, targets]) => [
    Number(chainId),
    new Map(targets.map((target, index) => [target.address.toLowerCase(), index])),
  ]),
);

/** Position in a chain's liquidity ranking, or undefined when a buy may not target the token there. */
export function buyRank(chainId: number, address: string): number | undefined {
  return ranks.get(chainId)?.get(address.toLowerCase());
}

/** Position in the Robinhood liquidity ranking, or undefined when a buy may not target the token. */
export function robinhoodBuyRank(address: string): number | undefined {
  return buyRank(4663, address);
}
